const { test, expect } = require('@playwright/test');
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
test.use({ channel: 'msedge', actionTimeout: 10000 });

test('public local Swagger, real login/JWT execute, multipart and documented response schemas', async ({ page }) => {
  test.setTimeout(120000);
  const origin = process.env.AUTH_TEST_ORIGIN;
  const samples = []; const external = [];
  page.on('request', r => { if (new URL(r.url()).origin !== origin) external.push(r.url()); });
  const record = async (response, path) => {
    const body = await response.json();
    const saved = JSON.parse(JSON.stringify(body));
    if (saved.accessToken) saved.accessToken = 'redacted.jwt.token';
    samples.push({ path, method: response.request().method(), status: response.status(), body: saved,
      requestId: response.headers()['x-request-id'], contentType: response.headers()['content-type'] });
    return body;
  };
  const request = async (path, template, token) => {
    const response = await page.request.get(origin + path, { headers: token ? { Authorization: 'Bearer ' + token } : {} });
    const body = await response.json();
    samples.push({ path: template, method: 'GET', status: response.status(), body,
      requestId: response.headers()['x-request-id'], contentType: response.headers()['content-type'] });
    return { status: response.status(), body };
  };
  await page.goto(origin + '/docs/');
  await expect(page.locator('.swagger-ui .info .title')).toContainText('Product import API');
  expect((await page.request.get(origin + '/docs/missing.json')).status()).toBe(404);
  const list = page.locator('#operations-Products-listProducts');
  await list.locator('.opblock-summary').click();
  await list.getByRole('button', { name: 'Try it out' }).click();
  let response = page.waitForResponse(r => new URL(r.url()).pathname === '/api/products');
  await list.getByRole('button', { name: 'Execute', exact: true }).click();
  const denied = await response; expect(denied.status()).toBe(401); await record(denied, '/api/products');
  const login = page.locator('#operations-Auth-login');
  await login.locator('.opblock-summary').click();
  await login.getByRole('button', { name: 'Try it out' }).click();
  await login.locator('textarea').fill(JSON.stringify({ username: 'fixture-user', password: 'password' }));
  response = page.waitForResponse(r => r.url().endsWith('/api/auth/login'));
  await login.getByRole('button', { name: 'Execute', exact: true }).click();
  const logged = await response; expect(logged.status()).toBe(200);
  const token = (await record(logged, '/api/auth/login')).accessToken;
  await page.locator('.auth-wrapper button.authorize').click();
  await page.locator('.auth-container input').fill(token);
  await page.locator('.auth-btn-wrapper button.authorize').click();
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  response = page.waitForResponse(r => new URL(r.url()).pathname === '/api/products');
  await list.getByRole('button', { name: 'Execute', exact: true }).click();
  const allowed = await response; expect(allowed.status()).toBe(200);
  expect(allowed.request().headers()['authorization']).toBe('Bearer ' + token);
  const products = await record(allowed, '/api/products');
  expect(products.pagination.total).toBe(48); expect(products.items[0].externalCode).toBe('FIX-0001');
  expect((await request('/api/products/1', '/api/products/{id}', token)).body.images).toHaveLength(1);
  expect((await request('/api/products?limit=0', '/api/products', token)).status).toBe(400);
  expect((await request('/api/health', '/api/health')).status).toBe(200);
  expect((await request('/api/_diagnostics', '/api/_diagnostics')).status).toBe(200);
  const upload = page.locator('#operations-Imports-createImport');
  await upload.locator('.opblock-summary').click();
  await upload.getByRole('button', { name: 'Try it out' }).click();
  await upload.locator('input[type=file]').setInputFiles(process.env.DOCS_XLSX);
  response = page.waitForResponse(r => new URL(r.url()).pathname === '/api/imports' && r.request().method() === 'POST');
  await upload.getByRole('button', { name: 'Execute', exact: true }).click();
  const accepted = await response; expect(accepted.status()).toBe(202);
  const id = (await record(accepted, '/api/imports')).jobId;
  expect((await request('/api/imports/' + id, '/api/imports/{id}', token)).body.status).toBe('queued');
  const args = JSON.parse(process.env.DOCS_COMPOSE_ARGS);
  if (!args.includes('product-import-docs-check')) throw new Error('Wrong docs test project');
  execFileSync(process.env.DOCS_DOCKER, args.concat(['up', '-d', '--no-deps', 'worker']), { timeout: 60000, stdio: 'pipe' });
  await expect.poll(async () => (await request('/api/imports/' + id, '/api/imports/{id}', token)).body.status, { timeout: 30000 }).toBe('completed_with_errors');
  const issues = await request('/api/imports/' + id + '/issues?page=1&limit=50', '/api/imports/{id}/issues', token);
  expect(issues.body.pagination.total).toBe(2);
  expect((await request('/api/imports/00000000-0000-4000-8000-000000000000', '/api/imports/{id}', token)).status).toBe(404);
  await page.screenshot({ path: 'swagger-jwt.png', fullPage: true });
  await page.reload();
  await expect(page.locator('.swagger-ui .info .title')).toBeVisible();
  expect(await page.evaluate(() => window.ui.authSelectors.authorized().size)).toBe(0);
  expect(external).toEqual([]);
  fs.writeFileSync(process.env.DOCS_RESPONSES, JSON.stringify(samples, null, 2));
});
